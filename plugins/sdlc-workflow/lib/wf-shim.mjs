// The stable entry point of wf.mjs: `~/.sdlc/bin/wf.mjs` (SDLC_HOME/bin in tests).
//
// The path of the plugin carries its version, so a command that a session saved before an
// update names a folder that the update removes. The shim has one path on every host. Each
// session start writes `bin/wf-current.json`, which names the wf.mjs of the plugin that started
// the session; the shim loads that wf.mjs at each call. The shim itself never changes.
import { existsSync, mkdirSync, readFileSync, renameSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { sdlcHomeDir } from './home.mjs';

export const SHIM_VERSION = 1;

const SHIM = `#!/usr/bin/env node
// ~/.sdlc/bin/wf.mjs: the stable entry point of the sdlc-workflow wf.mjs (shim ${SHIM_VERSION}).
// It runs the wf.mjs that bin/wf-current.json names. Each session start of the plugin writes
// that file, so the shim follows the installed plugin version. Do not edit this file.
import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
let current;
try { current = JSON.parse(readFileSync(join(here, 'wf-current.json'), 'utf8')); } catch {
  process.stderr.write('wf.mjs shim: bin/wf-current.json is missing; start a session with the sdlc-workflow plugin, or run node "<skill-dir>/scripts/wf.mjs"\\n');
  process.exit(2);
}
const { main } = await import(pathToFileURL(current.cli).href);
process.exitCode = await main(process.argv.slice(2));
`;

export const shimDir = () => join(sdlcHomeDir(), 'bin');
export const shimPath = () => join(shimDir(), 'wf.mjs');

function writeIfChanged(file, text) {
  try { if (readFileSync(file, 'utf8') === text) return false; } catch { /* a new file */ }
  const tmp = `${file}.${process.pid}.tmp`;
  writeFileSync(tmp, text);
  renameSync(tmp, file);
  return true;
}

/**
 * Order two plugin versions such as `10.0.0-next.18` and `9.191.1`: negative when `a` is older.
 * A release sorts after its prereleases. A missing or unreadable version sorts first.
 */
export function compareVersions(a, b) {
  const parse = (v) => {
    const m = /^(\d+)\.(\d+)\.(\d+)(?:-([0-9A-Za-z.-]+))?/.exec(String(v ?? ''));
    return m ? { core: [Number(m[1]), Number(m[2]), Number(m[3])], pre: m[4] ? m[4].split('.') : null } : null;
  };
  const x = parse(a);
  const y = parse(b);
  if (!x || !y) return (x ? 1 : 0) - (y ? 1 : 0);
  for (let i = 0; i < 3; i++) if (x.core[i] !== y.core[i]) return x.core[i] - y.core[i];
  if (!x.pre || !y.pre) return (x.pre ? -1 : 0) - (y.pre ? -1 : 0);
  for (let i = 0; i < Math.max(x.pre.length, y.pre.length); i++) {
    const p = x.pre[i];
    const q = y.pre[i];
    if (p === undefined || q === undefined) return p === undefined ? -1 : 1;
    if (p === q) continue;
    const pn = /^\d+$/.test(p);
    const qn = /^\d+$/.test(q);
    if (pn && qn) return Number(p) - Number(q);
    if (pn !== qn) return pn ? -1 : 1;
    return p < q ? -1 : 1;
  }
  return 0;
}

/**
 * Write the shim and name the wf.mjs of `pluginRoot` as the current one. Returns
 * `{ shim, cli, changed }`. A failure never fails a session start; the caller ignores it.
 *
 * The pointer only moves forward. Sessions of several plugin versions run at the same time, and an
 * old session that resumes or compacts would otherwise point every saved command back at its old
 * version. A session of an older version leaves the pointer alone while the wf.mjs it names exists.
 */
export function writeShim(pluginRoot, { version = null, host = null } = {}) {
  const cli = join(pluginRoot, 'scripts', 'wf.mjs');
  if (!existsSync(cli)) throw new Error(`no wf.mjs at ${cli}`);
  mkdirSync(shimDir(), { recursive: true });
  const a = writeIfChanged(shimPath(), SHIM);
  const current = { cli, pluginRoot, version, host, shim: SHIM_VERSION };
  const old = readShimCurrent();
  if (old && old.cli !== cli && old.cli && existsSync(old.cli) && compareVersions(version, old.version) < 0) {
    return { shim: shimPath(), cli: old.cli, changed: a, kept: old.version };
  }
  const b = !old || old.cli !== cli || old.version !== version
    ? writeIfChanged(join(shimDir(), 'wf-current.json'), `${JSON.stringify({ ...current, at: new Date().toISOString() }, null, 2)}\n`)
    : false;
  return { shim: shimPath(), cli, changed: a || b };
}

export function readShimCurrent() {
  try { return JSON.parse(readFileSync(join(shimDir(), 'wf-current.json'), 'utf8')); } catch { return null; }
}

/** The problems of the shim on this machine, for the doctor: an empty list when it works. */
export function shimProblems() {
  const problems = [];
  if (!existsSync(shimPath())) return [`no shim at ${shimPath()}: a session start writes it`];
  if (readFileSync(shimPath(), 'utf8') !== SHIM) problems.push(`${shimPath()} is not shim ${SHIM_VERSION}: the next session start rewrites it`);
  const current = readShimCurrent();
  if (!current) problems.push(`${join(shimDir(), 'wf-current.json')} is missing or unreadable`);
  else if (!existsSync(current.cli)) problems.push(`wf-current.json names ${current.cli}, which is gone: start a session to point it at the installed plugin`);
  return problems;
}
